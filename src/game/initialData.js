// Builds a demo history object for the last `days` days, biased toward
// completion by `hitRate` (0-1). Always relative to "today" so a fresh
// install looks populated regardless of when it's actually run.
function demoHistory(days, hitRate) {
  const history = {}
  for (let i = 1; i <= days; i++) {
    const key = dateKey(addDays(new Date(), -i))
    history[key] = Math.random() < hitRate
  }
  return history
}

